  window.acceptCookieConsent = function() {
    localStorage.setItem('fengoo_cookie_consent', 'true');
    const banner = document.getElementById('fengoo-cookie-consent');
    if (banner) {
      banner.style.opacity = '0';
      setTimeout(() => banner.remove(), 300);
    }
  };

  // Init
