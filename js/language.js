  // Reliable Google Translate combo trigger with retry mechanism
  function triggerGoogleCombo(langCode) {
    let count = 0;
    const interval = setInterval(() => {
      count++;
      const combo = document.querySelector('.goog-te-combo');
      if (combo) {
        clearInterval(interval);
        if (combo.value !== langCode) {
          combo.value = langCode;
          combo.dispatchEvent(new Event('change', { bubbles: true }));
          combo.dispatchEvent(new Event('input', { bubbles: true }));
        }
      } else if (count > 30) {
        clearInterval(interval);
      }
    }, 150);
  }

  // Connect with Google Translate widget
  function syncGoogleTranslate(langCode) {
    if (langCode === 'hi') {
      deleteCookie('googtrans');
      triggerGoogleCombo('hi');
      return;
    }

    setCookie('googtrans', '/auto/' + langCode);
    setCookie('googtrans', '/hi/' + langCode);
    triggerGoogleCombo(langCode);
  }

  // Public Language Switch Function
  window.changeFengooLanguage = function(langCode) {
    localStorage.setItem('fengoo_user_lang', langCode);
    const langObj = INDIAN_LANGUAGES.find(l => l.code === langCode) || INDIAN_LANGUAGES[0];

    // 1. Instant full-page DOM translation
    translatePageDOM(langCode);

    // 2. Google Translate hook
    syncGoogleTranslate(langCode);

    // 3. UI feedback
    closeLanguageModal();
    showLanguageToast(langObj);
  };

